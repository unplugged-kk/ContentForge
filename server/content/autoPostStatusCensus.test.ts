import { test, describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

import {
  AUTO_GENERATED_POST_STATUS,
  PRE_APPROVED_AUTO_POST_STATUS,
  PUBLISHABLE_STATUSES,
  autoGeneratedStatusFor,
  isPublishable,
  occupiesSlot,
} from "./postStatus";

const SERVER_ROOT = join(import.meta.dirname, "..");

/** Files that generate content without a human asking for that specific post. */
const AUTO_WRITERS = ["autopilot.ts", "rssAutopost.ts", "youtubeConnector.ts"];

function serverFiles(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) serverFiles(p, out);
    else if (
      name.endsWith(".ts") &&
      !name.endsWith(".test.ts") &&
      !name.endsWith(".dbtest.ts")
    ) {
      out.push(p);
    }
  }
  return out;
}

type CallSite = { file: string; line: number; statusExpr: string };

/** Every `storage.createPost(` call site with the status expression it supplies. */
function createPostSites(): CallSite[] {
  const sites: CallSite[] = [];
  for (const file of serverFiles(SERVER_ROOT)) {
    const lines = readFileSync(file, "utf8").split("\n");
    for (let i = 0; i < lines.length; i++) {
      if (!lines[i].includes("storage.createPost(")) continue;
      const window = lines.slice(i, i + 22).join("\n");
      const m = window.match(/status:\s*([^,\n]+)/);
      sites.push({
        file: file.replace(SERVER_ROOT + "/", ""),
        line: i + 1,
        statusExpr: m ? m[1].trim() : "",
      });
    }
  }
  return sites;
}

describe("D23 · an auto-generated post is never born publishable", () => {
  test("A1 the default auto status is 'draft'", () => {
    assert.equal(AUTO_GENERATED_POST_STATUS, "draft");
  });

  test("A2 a missing/NULL requireApproval yields a draft, not a publishable post", () => {
    assert.equal(autoGeneratedStatusFor(undefined), "draft");
    assert.equal(autoGeneratedStatusFor(null), "draft");
    assert.equal(autoGeneratedStatusFor(true), "draft");
  });

  test("A3 an explicit approval bypass still cannot publish", () => {
    const preApproved = autoGeneratedStatusFor(false);
    assert.equal(preApproved, PRE_APPROVED_AUTO_POST_STATUS);
    assert.equal(
      isPublishable(preApproved),
      false,
      "a pre-approved auto post must not be pickable by the scheduler",
    );
    assert.equal(occupiesSlot(preApproved), true);
  });

  test("A4 no value autoGeneratedStatusFor can return is publishable", () => {
    for (const flag of [true, false, null, undefined]) {
      const status = autoGeneratedStatusFor(flag);
      assert.equal(
        (PUBLISHABLE_STATUSES as readonly string[]).includes(status),
        false,
        `requireApproval=${String(flag)} produced publishable status ${status}`,
      );
    }
  });
});

describe("D23 · the census: every auto writer in the tree obeys the rule", () => {
  test("D1 the census finds the auto writers (guards against a green no-op)", () => {
    const sites = createPostSites().filter((s) =>
      AUTO_WRITERS.includes(s.file),
    );
    assert.ok(
      sites.length >= 7,
      `expected the known auto-generation call sites, found ${sites.length}: ${JSON.stringify(sites)}`,
    );
    for (const writer of AUTO_WRITERS) {
      assert.ok(
        sites.some((s) => s.file === writer),
        `census did not see ${writer} — the scan is broken, not the code`,
      );
    }
  });

  test("D2 no auto writer supplies a publishable status inline", () => {
    const offenders = createPostSites()
      .filter((s) => AUTO_WRITERS.includes(s.file))
      .filter((s) => /["']scheduled["']/.test(s.statusExpr));

    assert.deepEqual(
      offenders,
      [],
      `auto writer(s) can be born publishable: ${offenders
        .map((o) => `${o.file}:${o.line} status: ${o.statusExpr}`)
        .join(", ")}`,
    );
  });

  test("D3 every non-human writer goes through the named status helpers", () => {
    const strays = createPostSites()
      .filter((s) => AUTO_WRITERS.includes(s.file))
      .filter(
        (s) =>
          !/AUTO_GENERATED_POST_STATUS|autoGeneratedStatusFor/.test(s.statusExpr),
      );
    assert.deepEqual(
      strays,
      [],
      `auto writer status must come from postStatus.ts: ${strays
        .map((o) => `${o.file}:${o.line} ${o.statusExpr}`)
        .join(", ")}`,
    );
  });
});
